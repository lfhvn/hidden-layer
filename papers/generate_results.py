#!/usr/bin/env python3
"""
Regenerate the numbers that papers cite, straight from experiments.

This is the glue that makes "publish" reproducible: instead of transcribing results
into LaTeX by hand (where they go stale), each bound paper declares a generator here
that runs the (offline, deterministic) experiment and writes LaTeX into ``generated/``:

  - ``generated/<paper>_macros.tex`` : ``\\newcommand`` per (arm, metric) -> \\input in the preamble
  - ``generated/<paper>_table.tex``  : a results ``table`` -> \\input in the body
  - ``figures/<paper>_*.png``        : optional figures (only if matplotlib is installed)

Run:  python papers/generate_results.py            # regenerate all bound papers
      python papers/generate_results.py metacognition

All generators must be deterministic so ``make results`` produces identical output on
every machine (the metacognition generator uses the harness ``sim`` provider).
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Callable, Dict, List

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

PAPERS_DIR = REPO_ROOT / "papers"
GENERATED = PAPERS_DIR / "generated"
FIGURES = PAPERS_DIR / "figures"

_AUTOGEN_HEADER = (
    "% AUTO-GENERATED by papers/generate_results.py -- do not edit by hand.\n"
    "% Regenerate with: make -C papers results\n"
)


def _write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_AUTOGEN_HEADER + body + "\n")
    print(f"  wrote {path.relative_to(REPO_ROOT)}")


# --------------------------------------------------------------- metacognition


def generate_metacognition() -> None:
    """Calibration across four profiles -> macros + table (+ optional figure)."""
    from harness import analysis
    from theory_of_mind.metacognition import (
        SimulatedSubject,
        confidence_auroc,
        make_arithmetic_dataset,
        plot_reliability,
        run_calibration,
    )

    dataset = make_arithmetic_dataset(n=1500, seed=42)
    profiles = ["calibrated", "overconfident", "underconfident", "random"]

    rows: List[Dict] = []
    reports = {}
    for profile in profiles:
        run = run_calibration(SimulatedSubject(accuracy=0.7, profile=profile, seed=7), dataset)
        r = run.report
        reports[profile] = r
        confs = [rec.confidence for rec in run.records]
        corr = [rec.correct for rec in run.records]
        rows.append(
            {
                "arm": profile,
                "n": r.n,
                "accuracy": round(r.accuracy, 4),
                "ece": round(r.ece, 4),
                "mce": round(r.mce, 4),
                "brier": round(r.brier, 4),
                "auroc": round(confidence_auroc(confs, corr), 4),
            }
        )

    macros = analysis.latex_macros(rows, metrics=["accuracy", "ece", "mce", "brier", "auroc"], prefix="mc")
    _write(GENERATED / "metacognition_macros.tex", macros)

    table = analysis.to_latex(
        rows,
        columns=["arm", "accuracy", "ece", "mce", "brier", "auroc"],
        caption="Calibration of four simulated subjects on 1{,}500 deterministic factual "
        "items (offline \\texttt{sim} provider, seed 7). ECE/MCE/Brier lower is better; "
        "AUROC measures whether confidence ranks correct above incorrect answers.",
        label="tab:mc-calibration",
    )
    _write(GENERATED / "metacognition_table.tex", table)

    # Optional figure (only if matplotlib is available; the paper guards the \includegraphics).
    fig = plot_reliability(
        reports["overconfident"], str(FIGURES / "metacognition_reliability.png"), title="Overconfident subject"
    )
    if fig:
        print(f"  wrote {Path(fig).relative_to(REPO_ROOT)}")
    else:
        print("  (matplotlib absent -> skipped reliability figure; paper renders without it)")


GENERATORS: Dict[str, Callable[[], None]] = {
    "metacognition": generate_metacognition,
}


def main(argv: List[str]) -> int:
    targets = argv or list(GENERATORS)
    unknown = [t for t in targets if t not in GENERATORS]
    if unknown:
        print(f"Unknown paper(s): {unknown}. Available: {list(GENERATORS)}")
        return 2
    for name in targets:
        print(f"[{name}] regenerating results...")
        GENERATORS[name]()
    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
